-- ══ 唯一約束 ═════════════════════════════════════════════════════════════
--
-- ⚠️ 這些不只是「資料整潔」——它們是併發下的最後裁決者。
-- 重複評論、OAuth 首次登入撞號、綠界回呼重送，全部靠資料庫這一層擋，
-- 而不是「先查再寫」。多實例部署也因此不需要分散式鎖。

alter table users add constraint uk_users_email unique (email);

alter table organizers add constraint uk_organizers_user unique (user_id);

alter table payments add constraint uk_payments_merchant_trade_no unique (merchant_trade_no);

alter table comments add constraint uk_comments_event_user unique (event_id, user_id);

alter table favorites add constraint uk_favorites_user_event unique (event_id, user_id);

alter table refresh_tokens add constraint uk_refresh_tokens_token_hash unique (token_hash);

alter table password_reset_tokens
    add constraint uk_password_reset_tokens_token_hash unique (token_hash);

alter table user_oauth_accounts
    add constraint uk_user_oauth_accounts_provider_uid unique (provider, provider_uid);

alter table user_oauth_accounts
    add constraint uk_user_oauth_accounts_user_provider unique (user_id, provider);


-- ══ 索引 ═════════════════════════════════════════════════════════════════

create index idx_comments_event_created   on comments (event_id, created_at);
create index idx_favorites_user_created   on favorites (user_id, created_at);
-- 逾時取消的排程每分鐘掃一次，靠這條避免全表掃描
create index idx_orders_status_expires_at on orders (status, expires_at);
create index idx_refresh_tokens_family_id on refresh_tokens (family_id);
create index idx_tickets_order_item       on tickets (order_item_id);


